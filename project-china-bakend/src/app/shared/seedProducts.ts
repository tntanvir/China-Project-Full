export const seedProductsAndCategories = async () => {
  try {
    // 1. Seed Categories
    for (const cat of initialCategories) {
      await prisma.productCategory.upsert({
        where: { slug: cat.slug },
        update: {
          name: cat.name,
          description: cat.description,
          order: cat.order,
        },
        create: {
          name: cat.name,
          slug: cat.slug,
          description: cat.description,
          order: cat.order,
        },
      });
    }

    // 2. Seed Brands
    for (const b of initialBrands) {
      await (prisma as any).brand.upsert({
        where: { slug: b.slug },
        update: {
          name: b.name,
          category: b.category,
          country: b.country,
          website: b.website,
          description: b.description,
          status: b.status,
          isVerified: b.isVerified,
          order: b.order,
        },
        create: {
          name: b.name,
          slug: b.slug,
          category: b.category,
          country: b.country,
          website: b.website,
          description: b.description,
          status: b.status,
          isVerified: b.isVerified,
          order: b.order,
        },
      });
    }

    // 3. Check if products exist
    const count = await prisma.product.count();
    if (count === 0) {
      console.log("📦 Seeding default inventory products...");
      for (const prod of initialProducts) {
        await prisma.product.create({
          data: {
            name: prod.name,
            slug: prod.slug,
            category: prod.category,
            description: prod.description,
            specifications: prod.specifications,
            images: prod.images,
            minOrderQty: prod.minOrderQty,
            leadTimeDays: prod.leadTimeDays,
            isFeatured: prod.isFeatured,
            tags: prod.tags,
            status: prod.status,
            price: prod.price,
            stock: prod.stock,
            rating: prod.rating,
            reviewCount: prod.reviewCount,
          },
        });
      }
      console.log(`✅ Seeded ${initialProducts.length} default inventory products.`);
    }
  } catch (error) {
    console.error("❌ Failed to seed products, brands and categories:", error);
  }
};
